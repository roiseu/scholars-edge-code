"""Check that references exist, using the free Crossref REST API."""
import time
import requests
from difflib import SequenceMatcher

CROSSREF = "https://api.crossref.org/works"
# Crossref asks users to identify themselves with a contact email.
HEADERS = {"User-Agent": "ScholarsEdge-RefCheck/1.0 (mailto:you@university.edu)"}

def similarity(a, b):
    return SequenceMatcher(None, a.lower(), b.lower()).ratio()

def check_reference(title, doi=None):
    """Return (status, matched_title, matched_doi)."""
    if doi:
        r = requests.get(f"{CROSSREF}/{doi}", headers=HEADERS, timeout=20)
        if r.status_code != 200:
            return "DOI NOT FOUND", None, doi
        found = r.json()["message"].get("title", [""])[0]
        ok = similarity(title, found) > 0.85
        return ("VERIFIED" if ok else "DOI EXISTS - TITLE MISMATCH"), found, doi

    params = {"query.bibliographic": title, "rows": 1}
    r = requests.get(CROSSREF, params=params, headers=HEADERS, timeout=20)
    r.raise_for_status()
    items = r.json()["message"]["items"]
    if not items:
        return "NOT FOUND", None, None
    found = items[0].get("title", [""])[0]
    ok = similarity(title, found) > 0.85
    return ("LIKELY MATCH" if ok else "CHECK MANUALLY"), found, items[0].get("DOI")

references = [
    {"title": "Fabrication and errors in the bibliographic citations generated by ChatGPT"},
    {"title": "GPT detectors are biased against non-native English writers"},
    {"title": "A unified theory of quantum federated intrusion graphs"},  # invented
]

for ref in references:
    status, found, doi = check_reference(ref["title"], ref.get("doi"))
    print(f"[{status}] {ref['title'][:65]}")
    if found:
        print(f"     -> {found[:65]}  (DOI: {doi})")
    time.sleep(1)  # be polite to the API
